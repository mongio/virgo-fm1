"""VIRGO's antialiased fonts: Inter (SIL OFL 1.1, Rasmus Andersson) rasterised to 4-bit coverage.

    python3 tools/gen_aafont.py [INTER_DIR]   ->  firmware/gen/virgo_font.h

Each font: ASCII 32..126 plus a few signs at 127.. (see EXTRA). A glyph is a box bw x h (h = the line's
height, the baseline at asc), 4 bits a pixel, two pixels a byte, rows padded to a byte; bx = where the box
starts from the pen (may be negative); adv = the pen's step."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

R = Path(__file__).resolve().parent.parent
INTER = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/usr/share/fonts/opentype/inter")
EXTRA = ["☉", "→", "≤", "×", "À", "·", "°", "É"]   # 127 sun, 128 arrow, 129 <=, 130 x, 131 A grave, 132 dot, 133 degree, 134 E acute (0.4)
FONTS = [  # name, file, em px, tracking (px)
    ("F_XS", "Inter-SemiBold.otf", 9, 0.3),
    ("F_SM", "Inter-SemiBold.otf", 11, 0.4),
    ("F_MD", "Inter-SemiBold.otf", 16, 0.0),
    ("F_TI", "Inter-Bold.otf", 14, 0.2),
    ("F_XL", "Inter-Bold.otf", 30, 0.0),
]


def sun(sz, h, asc):
    """the solar mass sign, drawn: a ring and a dot, cap height"""
    cap = round(sz * 0.727)
    d = cap
    s = 4
    im = Image.new("L", ((d + 2) * s, h * s), 0)
    dr = ImageDraw.Draw(im)
    top = (asc - cap) * s
    w = max(1, round(sz * 0.09 * s))
    dr.ellipse([s, top, (d + 1) * s - 1, top + d * s - 1], outline=255, width=w)
    c = (d + 2) * s / 2
    r = max(1.2, sz * 0.08) * s
    dr.ellipse([c - r, top + d * s / 2 - r, c + r, top + d * s / 2 + r], fill=255)
    return im.resize((d + 2, h), Image.LANCZOS), d + 2


def build(name, file, em, track):
    f = ImageFont.truetype(str(INTER / file), em)
    asc, desc = f.getmetrics()
    h = asc + desc
    chars = [chr(c) for c in range(32, 127)] + EXTRA
    advs, bws, bxs, offs, data = [], [], [], [], bytearray()
    for ch in chars:
        if ch == "☉":
            g, adv = sun(em, h, asc)
            bx, bw = 0, g.size[0]
            adv += 1
        else:
            adv = round(f.getlength(ch) + track)
            l, t, r, b = f.getbbox(ch)
            l = min(l, 0) - 1
            r = max(r, 1) + 1
            bw = r - l
            g = Image.new("L", (bw, h), 0)
            ImageDraw.Draw(g).text((-l, 0), ch, font=f, fill=255)
            bx = l
        offs.append(len(data))
        px = g.load()
        for y in range(h):
            row = [px[x, y] for x in range(bw)]
            row += [0] * (bw & 1)
            for x in range(0, len(row), 2):
                a, b2 = (row[x] + 8) // 17, (row[x + 1] + 8) // 17
                data.append(min(a, 15) << 4 | min(b2, 15))
        advs.append(adv)
        bws.append(bw)
        bxs.append(bx)
    first, last = 32, 32 + len(chars) - 1

    def arr(t, n, v):
        lines = []
        for i in range(0, len(v), 24):
            lines.append("    " + ", ".join(str(x) for x in v[i:i + 24]) + ",")
        return f"static const {t} {name}_{n}[] = {{\n" + "\n".join(lines) + "\n};\n"
    out = f"/* {name}: Inter {file} at {em} px (SIL OFL 1.1), line {h}, baseline {asc} */\n"
    out += arr("uint8_t", "adv", advs) + arr("uint8_t", "bw", bws) + arr("int8_t", "bx", bxs) + arr("uint16_t", "off", offs)
    out += arr("uint8_t", "data", list(data))
    out += f"static const aafont_t {name} = {{{h}, {asc}, {first}, {last}, {name}_adv, {name}_bw, {name}_bx, {name}_off, {name}_data}};\n\n"
    return out, len(data)


def main():
    body = ["/* generated by tools/gen_aafont.py: do not edit */\n"]
    total = 0
    for spec in FONTS:
        s, n = build(*spec)
        body.append(s)
        total += n
    (R / "firmware" / "gen" / "virgo_font.h").write_text("".join(body))
    print("firmware/gen/virgo_font.h", total, "B of glyphs")


if __name__ == "__main__":
    main()
