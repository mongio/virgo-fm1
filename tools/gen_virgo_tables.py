"""VIRGO's tables, worked out here so the FM-1 needs no floating point.

    python3 tools/gen_virgo_tables.py   ->  firmware/gen/virgo_tables.h

  SIN_T      a cycle in 1024 steps (+1), Q15
  LOG2_T     log2(1 + i/256), i = 0..256, Q16
  EXP2_T     2^(i/256), i = 0..256, Q16 (1.0 = 65536)
  QNM_R, QNM_Q   the quasi-normal modes of a Kerr black hole by its spin a = i/100 (i = 0..99), from the fits of
             Berti, Cardoso and Will (Phys. Rev. D 73, 064030, 2006, table VIII): for the modes (2,2,0), (3,3,0),
             (2,2,1), (4,4,0): the frequency over the (2,2,0)'s (Q12) and the quality factor Q (Q8)
  OMEGA22    M*omega of (2,2,0) by spin, Q16 (for the screen: the final mass's frequency)
  CAT        a catalogue of detections (rounded values from the GWTC catalogues): name, m1, m2 (tenths of a solar
             mass), the remnant's spin (hundredths), the distance (Mpc)
"""
import math
from pathlib import Path

R = Path(__file__).resolve().parent.parent

# (f1, f2, f3, q1, q2, q3): M omega = f1 + f2 (1-a)^f3, Q = q1 + q2 (1-a)^q3
FITS = {
    (2, 2, 0): (1.5251, -1.1568, 0.1292, 0.7000, 1.4187, -0.4990),
    (3, 3, 0): (1.8956, -1.3043, 0.1818, 0.9000, 2.3430, -0.4810),
    (2, 2, 1): (1.3673, -1.0260, 0.1628, 0.1000, 0.5436, -0.4731),
    (4, 4, 0): (2.3000, -1.5056, 0.2244, 1.1929, 3.1191, -0.4825),
}
MODES = [(2, 2, 0), (3, 3, 0), (2, 2, 1), (4, 4, 0)]

CAT = [  # name, m1, m2, final spin, distance Mpc (rounded, GWTC-1..4)
    ("GW150914", 35.6, 30.6, 0.69, 440),
    ("GW151226", 13.7, 7.7, 0.74, 450),
    ("GW170104", 30.8, 20.0, 0.66, 990),
    ("GW170608", 11.0, 7.6, 0.69, 320),
    ("GW170814", 30.6, 25.2, 0.72, 580),
    ("GW170817", 1.46, 1.27, 0.20, 40),
    ("GW190412", 30.1, 8.3, 0.67, 740),
    ("GW190521", 85.0, 66.0, 0.72, 5300),
    ("GW190814", 23.2, 2.6, 0.28, 240),
    ("GW200115", 5.7, 1.5, 0.38, 300),
    ("GW230529", 3.6, 1.4, 0.45, 200),
    ("GW231123", 99.0, 99.0, 0.85, 2200),
]


def qnm(mode, a):
    f1, f2, f3, q1, q2, q3 = FITS[mode]
    return f1 + f2 * (1 - a) ** f3, q1 + q2 * (1 - a) ** q3


def arr(t, name, v, per=16):
    lines = ["    " + ", ".join(str(x) for x in v[i:i + per]) + "," for i in range(0, len(v), per)]
    tab = " VTAB" if name in ("SIN_T", "LOG2_T", "EXP2_T") else ""   # 0.4.1: the audio's hot tables in RAM on the chip
    return f"static const {t} {name}[{len(v)}]{tab} = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    out = ["/* generated by tools/gen_virgo_tables.py: do not edit */\n"]
    out.append(arr("int16_t", "SIN_T", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]))
    out.append(arr("uint32_t", "LOG2_T", [round(65536 * math.log2(1 + i / 256)) for i in range(257)], 12))
    out.append(arr("uint32_t", "EXP2_T", [round(65536 * 2 ** (i / 256)) for i in range(257)], 12))
    steps = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
             107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
             876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871,
             5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
             27086, 29794, 32767]
    out.append(arr("int16_t", "ADPCM_STEP", steps, 16))
    out.append(arr("int8_t", "ADPCM_IDX", [-1, -1, -1, -1, 2, 4, 6, 8], 8))
    out.append(arr("uint8_t", "ATAN_T", [round(math.atan(i / 256) * 512 / math.pi) for i in range(257)], 24))
    r, q, w = [], [], []
    for i in range(100):
        a = i / 100
        w0, q0 = qnm((2, 2, 0), a)
        w.append(round(w0 * 65536))
        for m in MODES:
            wm, qm = qnm(m, a)
            r.append(round(4096 * wm / w0))
            q.append(round(256 * qm))
    out.append(arr("uint16_t", "QNM_R", r, 16))
    out.append(arr("uint16_t", "QNM_Q", q, 16))
    out.append(arr("uint32_t", "OMEGA22", w, 12))
    out.append(f"#define NCAT {len(CAT)}u\n")
    out.append("static const struct { char name[10]; uint16_t m1, m2; uint8_t spin; uint16_t mpc; } CAT[NCAT] = {\n")
    for n, m1, m2, a, d in CAT:
        out.append(f'    {{"{n}", {round(m1 * 10)}, {round(m2 * 10)}, {round(a * 100)}, {d}}},\n')
    out.append("};\n")
    (R / "firmware" / "gen" / "virgo_tables.h").write_text("".join(out))
    print("firmware/gen/virgo_tables.h")
    for i in (0, 50, 69, 99):
        print(f"a={i/100:.2f}", [(m, round(r[i * 4 + k] / 4096, 3), round(q[i * 4 + k] / 256, 2)) for k, m in enumerate(MODES)])


if __name__ == "__main__":
    main()
